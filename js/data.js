const STORAGE_KEY = "kintu_family_data_v6";

// -------------------------------------------------------
// LOCAL STORAGE (client-side cache / offline fallback)
// -------------------------------------------------------
function getFamilyData() {
  const local = localStorage.getItem(STORAGE_KEY);
  if (!local) {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(KINTU_INITIAL_DATA));
    return JSON.parse(JSON.stringify(KINTU_INITIAL_DATA));
  }
  try {
    const parsed = JSON.parse(local);
    // Ensure all seed members are present and parent/children relations intact
    if (!parsed.members || parsed.members.length < KINTU_INITIAL_DATA.members.length) {
      parsed.members = KINTU_INITIAL_DATA.members;
    } else {
      const localMap = new Map((parsed.members || []).map(m => [m.id, m]));
      KINTU_INITIAL_DATA.members.forEach(seedM => {
        if (!localMap.has(seedM.id)) {
          localMap.set(seedM.id, seedM);
        } else {
          const existing = localMap.get(seedM.id);
          const mergedChildren = Array.from(new Set([...(seedM.childrenIds || []), ...(existing.childrenIds || [])]));
          const mergedParents = Array.from(new Set([...(seedM.parentIds || []), ...(existing.parentIds || [])]));
          localMap.set(seedM.id, {
            ...existing,
            childrenIds: mergedChildren,
            parentIds: mergedParents
          });
        }
      });
      parsed.members = Array.from(localMap.values());
    }
    if (!parsed.gallery) parsed.gallery = [];
    if (!parsed.upcomingReunion) parsed.upcomingReunion = KINTU_INITIAL_DATA.upcomingReunion;
    if (!parsed.minutes || parsed.minutes.length < KINTU_INITIAL_DATA.minutes.length || !parsed.minutes[0]?.agenda) {
      parsed.minutes = KINTU_INITIAL_DATA.minutes;
    }
    if (!parsed.updates || !parsed.updates.length) parsed.updates = KINTU_INITIAL_DATA.updates;
    saveFamilyData(parsed);
    return parsed;
  } catch (e) {
    console.error("Failed parsing localStorage family data", e);
    return JSON.parse(JSON.stringify(KINTU_INITIAL_DATA));
  }
}

function saveFamilyData(data) {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
}

function resetFamilyDataToDefault() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(KINTU_INITIAL_DATA));
  return JSON.parse(JSON.stringify(KINTU_INITIAL_DATA));
}

