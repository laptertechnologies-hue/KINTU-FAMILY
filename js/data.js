async function fetchMembersFromDB() {
  try {
    const resp = await fetch("/api/members");
    if (!resp.ok) throw new Error("GET /api/members " + resp.status);
    const { members } = await resp.json();
    return members || [];
  } catch (err) {
    console.warn("Could not load members from DB (offline or local dev?):", err.message);
    return null; // null = use local cache
  }
}

async function saveMemberToDB(member) {
  try {
    const resp = await fetch("/api/members", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(member),
    });
    if (!resp.ok) throw new Error("POST /api/members " + resp.status);
    return true;
  } catch (err) {
    console.warn("Could not save member to DB:", err.message);
    return false;
  }
}

async function saveMembersBatchToDB(membersList) {
  const CHUNK = 20;
  try {
    for (let i = 0; i < membersList.length; i += CHUNK) {
      const resp = await fetch("/api/members", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(membersList.slice(i, i + CHUNK)),
      });
      if (!resp.ok) throw new Error("POST /api/members batch " + resp.status);
    }
    return true;
  } catch (err) {
    console.warn("Could not batch save members to DB:", err.message);
    return false;
  }
}

